def resolve_benchmark_path(test_path: str) -> str:
    """
    Resolves benchmark test_path intelligently whether run from repo root
    or from methods/spider-agent-jabuti/.
    """
    candidates = [
        test_path,
        os.path.join(SCRIPT_DIR, test_path),
        os.path.join(SCRIPT_DIR, "examples", os.path.basename(test_path)),
        os.path.join(os.getcwd(), "methods", "spider-agent-jabuti", test_path.lstrip("./")),
    ]
    for c in candidates:
        if os.path.isfile(c):
            return os.path.abspath(c)
    return os.path.abspath(test_path)


def load_task_configuration(
    task_id: str, test_path: str, task_dir: Optional[str] = None
) -> Tuple[Dict[str, Any], str]:
    """
    Locates and returns the task configuration dict and the source data directory.
    """
    resolved_test_path = resolve_benchmark_path(test_path)
    if not os.path.isfile(resolved_test_path):
        raise FileNotFoundError(
            f"Benchmark file '{test_path}' not found on disk. Tried: '{resolved_test_path}'"
        )

    task_config = None
    with open(resolved_test_path, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            record = json.loads(line)
            if (
                record.get("instance_id") == task_id
                or record.get("id") == task_id
            ):
                task_config = record
                break

    if task_config is None:
        raise ValueError(
            f"Task ID '{task_id}' not found in benchmark file '{resolved_test_path}'"
        )

    # Determine task source directory
    source_dir = None
    if task_dir:
        candidate_task_dirs = [
            task_dir,
            os.path.join(SCRIPT_DIR, task_dir),
            os.path.join(os.path.dirname(resolved_test_path), task_dir),
        ]
        for c in candidate_task_dirs:
            if os.path.isdir(c):
                source_dir = os.path.abspath(c)
                break

    if not source_dir:
        inferred_dirs = [
            os.path.join(os.path.dirname(resolved_test_path), task_id),
            os.path.join(SCRIPT_DIR, "examples", task_id),
        ]
        for c in inferred_dirs:
            if os.path.isdir(c):
                source_dir = os.path.abspath(c)
                break

    if not source_dir:
        source_dir = os.path.abspath(os.path.dirname(resolved_test_path))

    return task_config, source_dir



def determine_task_type(task_config: Dict[str, Any]) -> str:
    """Classifies task type (pg, local, bq, sf, dbt)."""
    instance_id = task_config.get("instance_id", "")
    if instance_id.startswith("bq") or instance_id.startswith("ga"):
        task_config["type"] = "Bigquery"
        return "bq"
    elif instance_id.startswith("local"):
        if task_config.get("type") == "PostgreSQL":
            return "pg"
        else:
            task_config["type"] = "Local"
            return "local"
    elif instance_id.startswith("sf"):
        task_config["type"] = "Snowflake"
        return "sf"
    else:
        return "dbt"


def execute_single_task(args: argparse.Namespace) -> int:
    """
    Executes a single benchmark task and produces all required artifacts.

    Returns:
        POSIX exit code:
        0 - Success (answer file result.csv generated)
        1 - Aborted / Repeated error / Exception
        2 - Timed out (exceeded max_steps)
    """
    output_dir = os.path.abspath(args.output_dir)
    setup_logging(output_dir)

    start_time = time.time()
    start_time_iso = datetime.datetime.now(datetime.timezone.utc).isoformat()

    logger.info("==================================================")
    logger.info("Starting Atomic Task Execution: %s", args.task_id)
    logger.info("Model: %s | Provider: %s", args.model, args.provider)
    logger.info("Output Directory: %s", output_dir)
    logger.info("==================================================")

    # Check for existing results (idempotence)
    result_json_path = os.path.join(output_dir, "spider", "result.json")
    result_csv_path = os.path.join(output_dir, "result.csv")

    if not args.overwriting and (
        os.path.exists(result_json_path) or os.path.exists(result_csv_path)
    ):
        if args.retry_failed and os.path.exists(result_json_path):
            try:
                with open(result_json_path, "r", encoding="utf-8") as f:
                    prev_result = json.load(f)
                if prev_result.get("finished", False) and not (
                    "FAIL" in str(prev_result.get("result", ""))
                    or "error" in str(prev_result.get("result", "")).lower()
                ):
                    logger.info("Previous run succeeded and --retry_failed specified. Skipping.")
                    return 0
                logger.info("Retrying previously failed task: %s", args.task_id)
            except Exception as e:
                logger.warning("Could not read previous result.json: %s", e)
        else:
            logger.info("Results already exist in %s and --overwriting is false. Skipping.", output_dir)
            return 0

    # Load task config
    try:
        task_config, task_source_dir = load_task_configuration(
            args.task_id, args.test_path, args.task_dir
        )
    except Exception as e:
        logger.error("Failed to load task configuration: %s", e)
        return 1

    task_type = determine_task_type(task_config)
    logger.info("Resolved task type: '%s' (declared type: '%s')", task_type, task_config.get("type"))

    # Prepare output directory
    if os.path.exists(output_dir):
        # Clean previous contents cleanly
        for item in os.listdir(output_dir):
            item_path = os.path.join(output_dir, item)
            try:
                if os.path.isdir(item_path):
                    shutil.rmtree(item_path)
                else:
                    os.remove(item_path)
            except Exception as e:
                logger.warning("Could not remove old item %s: %s", item_path, e)
    os.makedirs(output_dir, exist_ok=True)

    # Dynamic Sandbox Naming (strictly adheres to Section 5.1):
    # container_name = f"spider-jabuti-{model_tag}-{instance_id}-{uuid.uuid4().hex[:6]}"
    raw_model_tag = args.model.split("/")[-1]
    safe_model_tag = sanitize_docker_name(raw_model_tag)
    safe_instance_id = sanitize_docker_name(args.task_id)
    unique_suffix = uuid.uuid4().hex[:6]
    container_name = sanitize_docker_name(
        f"spider-jabuti-{safe_model_tag}-{safe_instance_id}-{unique_suffix}"
    )

    # Image selection
    if args.image_name:
        image_name = args.image_name
    elif task_type == "pg":
        image_name = "spider_agent_jabuti-image"
    else:
        image_name = "spider_agent-image"

    env_config = {
        "image_name": image_name,
        "init_args": {
            "name": container_name,
            "work_dir": "/workspace",
        },
    }

    if task_type == "pg":
        if args.docker_network:
            env_config["init_args"]["network_mode"] = args.docker_network
        env_config["init_args"]["environment"] = {
            "PGHOST": args.pg_host,
            "PGPORT": str(args.pg_port),
            "PGUSER": "postgres",
            "PGDATABASE": "jabuti_sql",
        }

    # Configure directory copy into container workspace
    task_config["config"] = [
        {
            "type": "copy_all_subfiles",
            "parameters": {"dirs": [task_source_dir]},
        }
    ]

    # Handle dry-run execution mode
    if args.dry_run:
        logger.info("[DRY RUN] Parameters and environment verified successfully.")
        logger.info("[DRY RUN] Generated container name: %s", container_name)
        logger.info("[DRY RUN] Task config: %s", task_config.get("question", ""))

        # Emit simulated dummy artifacts for validation
        dummy_csv = os.path.join(output_dir, "result.csv")
        with open(dummy_csv, "w", encoding="utf-8") as f:
            f.write("output\ndry_run_success\n")

        dummy_trajectory = {
            "Task": task_config.get("question", ""),
            "system_message": "Dry Run Mode",
            "trajectory": [
                {
                    "observation": "Dry run initial observation",
                    "thought": "Validating configuration",
                    "action": "Terminate(output='result.csv')",
                    "response": "Done",
                }
            ],
        }
        with open(
            os.path.join(output_dir, "trajectory.json"), "w", encoding="utf-8"
        ) as f:
            json.dump(dummy_trajectory, f, indent=2)

        os.makedirs(os.path.join(output_dir, "spider"), exist_ok=True)
        with open(
            os.path.join(output_dir, "spider", "result.json"), "w", encoding="utf-8"
        ) as f:
            json.dump(
                {
                    "finished": True,
                    "steps": 1,
                    "result": "result.csv",
                    "result_files": {},
                    **dummy_trajectory,
                },
                f,
                indent=2,
            )

        end_time = time.time()
        total_duration_ms = (end_time - start_time) * 1000.0
        end_time_iso = datetime.datetime.now(datetime.timezone.utc).isoformat()
        metrics = {
            "instance_id": args.task_id,
            "model": args.model,
            "provider": args.provider,
            "step_count": 1,
            "max_steps": args.max_steps,
            "finished": True,
            "done": True,
            "exit_code": 0,
            "t_total_ms": round(total_duration_ms, 2),
            "t_llm_ms": 0.0,
            "t_db_ms": 0.0,
            "tokens_prompt": 0,
            "tokens_completion": 0,
            "tokens_total": 0,
            "export_syntax": "NONE",
            "result_output": "result.csv",
            "has_result_csv": True,
            "csv_row_count": 1,
            "csv_sha256": calculate_sha256(dummy_csv),
            "start_time": start_time_iso,
            "end_time": end_time_iso,
            "error": None,
        }
        with open(os.path.join(output_dir, "metrics.json"), "w", encoding="utf-8") as f:
            json.dump(metrics, f, indent=2)

        prov = generate_provenance_record(
            task_config=task_config,
            model=args.model,
            provider=args.provider,
            temperature=args.temperature,
            top_p=args.top_p,
            output_dir=output_dir,
            container_name=container_name,
            image_name=image_name,
            step_count=1,
            total_duration_ms=total_duration_ms,
            t_llm_ms=0.0,
            t_db_ms=0.0,
            tokens_prompt=0,
            tokens_completion=0,
            tokens_total=0,
            export_syntax="NONE",
            exit_code=0,
            start_time_iso=start_time_iso,
            end_time_iso=end_time_iso,
            has_result_csv=True,
            pg_host=args.pg_host,
            pg_port=args.pg_port,
        )
        with open(
            os.path.join(output_dir, "task_provenance.json"), "w", encoding="utf-8"
        ) as f:
            json.dump(prov, f, indent=2)

        return 0

    # Initialize PromptAgent
    agent = PromptAgent(
        model=args.model,
        provider=args.provider,
        base_url=args.base_url,
        api_key=args.api_key,
        max_tokens=args.max_tokens,
        top_p=args.top_p,
        temperature=args.temperature,
        max_memory_length=args.max_memory_length,
        max_steps=args.max_steps,
        use_plan=args.plan,
    )

    env = None
    done = False
    result_output = ""
    trajectory = {"trajectory": []}
    result_files = {}
    error_message = None

    try:
        logger.info("Constructing Docker sandbox environment: %s", container_name)
        env = Spider_Agent_Env(
            env_config=env_config,
            task_config=task_config,
            cache_dir=args.cache_dir,
            mnt_dir=output_dir,
        )

        agent.set_env_and_task(env)
        logger.info(
            "Task instruction: %s",
            task_config.get("question", task_config.get("instruction", "")),
        )

        # Run agent ReAct loop
        done, result_output = agent.run()
        trajectory = agent.get_trajectory()

        # Run environment post-processing
        result_files = env.post_process()

    except Exception as e:
        logger.exception("Task execution encountered critical exception: %s", e)
        error_message = str(e)
        done = False
        result_output = f"EXCEPTION: {e}"
        try:
            trajectory = agent.get_trajectory()
        except Exception:
            pass

    finally:
        # Guarantee container destruction
        if env is not None:
            try:
                env.close()
                logger.info("Sandbox container %s cleanly destroyed.", container_name)
            except Exception as e:
                logger.warning("Error closing sandbox container %s: %s", container_name, e)

    end_time = time.time()
    total_duration_ms = (end_time - start_time) * 1000.0
    end_time_iso = datetime.datetime.now(datetime.timezone.utc).isoformat()
    step_count = len(trajectory.get("trajectory", []))

    # Clean local sqlite/duckdb remnants if applicable
    if task_type == "local":
        for file_path in glob.glob(os.path.join(output_dir, "*.sqlite")) + glob.glob(
            os.path.join(output_dir, "*.duckdb")
        ):
            try:
                os.remove(file_path)
            except Exception as e:
                logger.warning("Could not remove db file %s: %s", file_path, e)

    # -------------------------------------------------------------------------
    # Result File Normalization: Guarantee result.csv exists
    # -------------------------------------------------------------------------
    target_result_csv = os.path.join(output_dir, "result.csv")

    if not os.path.exists(target_result_csv):
        # 1. Check if result_output points to an existing file in output_dir
        cleaned_path = result_output.replace("/workspace/", "").strip()
        candidate_path = os.path.join(output_dir, cleaned_path)
        if cleaned_path and os.path.isfile(candidate_path):
            try:
                shutil.copyfile(candidate_path, target_result_csv)
                logger.info("Copied %s -> %s", candidate_path, target_result_csv)
            except Exception as e:
                logger.warning("Failed to copy candidate result file: %s", e)

        # 2. Check if a single CSV was added in result_files
        elif result_files.get("added_files"):
            added_csvs = [
                f for f in result_files["added_files"] if f.endswith(".csv")
            ]
            if len(added_csvs) == 1 and os.path.isfile(added_csvs[0]):
                try:
                    shutil.copyfile(added_csvs[0], target_result_csv)
                    logger.info("Copied added CSV %s -> %s", added_csvs[0], target_result_csv)
                except Exception as e:
                    logger.warning("Failed to copy added CSV file: %s", e)

        # 3. If agent outputted text or a scalar answer, format as RFC 4180 CSV
        elif done and result_output and not result_output.startswith("ERROR"):
            try:
                with open(target_result_csv, "w", newline="", encoding="utf-8") as f:
                    writer = csv.writer(f)
                    writer.writerow(["output"])
                    writer.writerow([result_output])
                logger.info("Generated result.csv from literal agent answer.")
            except Exception as e:
                logger.warning("Failed to write literal answer to result.csv: %s", e)

    has_result_csv = (
        os.path.exists(target_result_csv)
        and os.path.getsize(target_result_csv) > 0
    )

    # -------------------------------------------------------------------------
    # Determine POSIX Exit Code
    # -------------------------------------------------------------------------
    if error_message is not None:
        exit_code = 1
        logger.error("Task failed with exception: %s", error_message)
    elif "ERROR: Repeated action" in str(result_output):
        exit_code = 1
        logger.error("Task aborted: repeated identical action loop.")
    elif not done and step_count >= args.max_steps:
        exit_code = 2
        logger.warning("Task timed out: exceeded maximum steps (%d).", args.max_steps)
    elif not done:
        exit_code = 1
        logger.error("Task aborted before completion (done=False).")
    elif has_result_csv:
        exit_code = 0
        logger.info("Task completed successfully with valid result.csv.")
    else:
        exit_code = 1
        logger.error("Task finished (done=True) but result.csv was not generated.")

    # -------------------------------------------------------------------------
    # Persist Artifacts Contract
    # -------------------------------------------------------------------------
    # 1. trajectory.json
    with open(
        os.path.join(output_dir, "trajectory.json"), "w", encoding="utf-8"
    ) as f:
        json.dump(trajectory, f, indent=2, ensure_ascii=False)

    # 2. spider/result.json (backwards compatibility)
    os.makedirs(os.path.join(output_dir, "spider"), exist_ok=True)
    spider_result = {
        "finished": done,
        "steps": step_count,
        "result": result_output,
        "result_files": result_files,
        **trajectory,
    }
    with open(
        os.path.join(output_dir, "spider", "result.json"), "w", encoding="utf-8"
    ) as f:
        json.dump(spider_result, f, indent=2, ensure_ascii=False)

    # 3. metrics.json
    csv_hash = calculate_sha256(target_result_csv) if has_result_csv else None
    csv_row_count = 0
    if has_result_csv:
        try:
            with open(target_result_csv, "r", encoding="utf-8", errors="ignore") as f:
                csv_row_count = max(0, len(list(csv.reader(f))) - 1)
        except Exception:
            pass

    t_llm_ms = round(float(getattr(agent, "t_llm_ms", 0.0)), 2)
    t_db_ms = round(float(getattr(agent, "t_db_ms", 0.0)), 2)
    tokens_prompt = int(getattr(agent, "tokens_prompt", 0) or 0)
    tokens_completion = int(getattr(agent, "tokens_completion", 0) or 0)
    tokens_total = int(getattr(agent, "tokens_total", 0) or 0)
    export_syntax = getattr(agent, "export_syntax", "NONE")
    if not export_syntax or export_syntax == "NONE":
        export_syntax = detect_export_syntax(
            getattr(agent, "actions", []), result_output or "result.csv"
        )

    metrics = {
        "instance_id": args.task_id,
        "model": args.model,
        "provider": args.provider,
        "step_count": step_count,
        "max_steps": args.max_steps,
        "finished": done,
        "done": done,
        "exit_code": exit_code,
        "t_total_ms": round(total_duration_ms, 2),
        "t_llm_ms": t_llm_ms,
        "t_db_ms": t_db_ms,
        "tokens_prompt": tokens_prompt,
        "tokens_completion": tokens_completion,
        "tokens_total": tokens_total,
        "export_syntax": export_syntax,
        "result_output": result_output,
        "has_result_csv": has_result_csv,
        "csv_row_count": csv_row_count,
        "csv_sha256": csv_hash,
        "start_time": start_time_iso,
        "end_time": end_time_iso,
        "error": error_message,
    }
    with open(os.path.join(output_dir, "metrics.json"), "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2)

    # 4. task_provenance.json (W3C PROV-JSON)
    prov_record = generate_provenance_record(
        task_config=task_config,
        model=args.model,
        provider=args.provider,
        temperature=args.temperature,
        top_p=args.top_p,
        output_dir=output_dir,
        container_name=container_name,
        image_name=image_name,
        step_count=step_count,
        total_duration_ms=total_duration_ms,
        t_llm_ms=t_llm_ms,
        t_db_ms=t_db_ms,
        tokens_prompt=tokens_prompt,
        tokens_completion=tokens_completion,
        tokens_total=tokens_total,
        export_syntax=export_syntax,
        exit_code=exit_code,
        start_time_iso=start_time_iso,
        end_time_iso=end_time_iso,
        has_result_csv=has_result_csv,
        pg_host=args.pg_host,
        pg_port=args.pg_port,
    )
    with open(
        os.path.join(output_dir, "task_provenance.json"), "w", encoding="utf-8"
    ) as f:
        json.dump(prov_record, f, indent=2)

    logger.info("==================================================")
    logger.info("Task %s finished. Exit code: %d", args.task_id, exit_code)
    logger.info("Artifacts saved to: %s", output_dir)
    logger.info("==================================================")

    return exit_code


def main():
    args = parse_arguments()
    exit_code = execute_single_task(args)
    sys.exit(exit_code)


if __name__ == "__main__":
    main()
