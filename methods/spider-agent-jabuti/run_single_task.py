def setup_logging(output_dir: Optional[str] = None) -> None:
    """Configures stdout and file logging handlers."""
    # Ensure handlers are not duplicated
    if logger.handlers:
        return

    formatter = logging.Formatter(
        fmt="\x1b[1;33m[%(asctime)s \x1b[31m%(levelname)s \x1b[32m%(module)s/%(lineno)d-%(processName)s\x1b[1;33m] \x1b[0m%(message)s"
    )

    stdout_handler = logging.StreamHandler(sys.stdout)
    stdout_handler.setLevel(logging.INFO)
    stdout_handler.setFormatter(formatter)
    stdout_handler.addFilter(logging.Filter("spider_agent"))
    logger.addHandler(stdout_handler)

    os.makedirs("logs", exist_ok=True)
    datetime_str = datetime.datetime.now().strftime("%Y%m%d@%H%M%S")
    file_handler = logging.FileHandler(
        os.path.join("logs", f"task-{datetime_str}.log"), encoding="utf-8"
    )
    file_handler.setLevel(logging.INFO)
    file_handler.setFormatter(formatter)
    logger.addHandler(file_handler)

    if output_dir:
        os.makedirs(output_dir, exist_ok=True)
        task_log_handler = logging.FileHandler(
            os.path.join(output_dir, "task.log"), encoding="utf-8"
        )
        task_log_handler.setLevel(logging.DEBUG)
        task_log_handler.setFormatter(formatter)
        logger.addHandler(task_log_handler)


