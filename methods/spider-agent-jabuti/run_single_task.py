#!/usr/bin/env python3
"""
run_single_task.py — Atomic Single-Task Execution Harness for JABUTI-SQL / Spider2
===================================================================================

PURPOSE:
--------
Executes a single benchmark task in an isolated, atomic Docker sandbox environment.
Deconstructs the monolithic evaluation loop into an independently schedulable unit
designed for workflow engines (e.g. AkôFlow DAG orchestration).

KEY FEATURES:
-------------
1. Atomic execution: Runs a single task instance (--task_id) without outer loops.
2. Unique container isolation: Dynamically generates uniquely-keyed Docker container
   names (spider-jabuti-{model}-{instance_id}-{uuid}) preventing name collisions.
3. Standard POSIX exit codes:
   - 0: Task completed normally (answer file result.csv generated).
   - 1: Task aborted due to repeated error loop or exception.
   - 2: Task timed out (exceeded max_steps).
4. Standard Artifact Contract:
   - result.csv: Prediction table generated by the agent for evaluation.
   - trajectory.json: Full thought/action/observation micro-steps.
   - metrics.json: Granular execution telemetry (durations, steps, exit code).
   - task_provenance.json: W3C PROV-JSON scientific provenance graph.
   - spider/result.json: Backwards-compatible result format for existing evaluators.
"""

